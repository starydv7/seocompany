type EliteExtras = Pick<MarketingPage, "hero" | "console" | "orbit" | "systems" | "split"> & {
  services: { aside: string; kickers: string[]; accents: LuxAccentName[] };
};

/** Builds a full premium page from an existing D&D service plus page-specific hero, dashboard, orbit and standards. */
function fromElite(service: EliteService, extras: EliteExtras): MarketingPage {
  const { offerings } = service;
  return {
    route: service.route,
    name: service.name,
    accent: service.accent,
    hero: extras.hero,
    console: extras.console,
    ticker: service.ticker,
    services: {
      eyebrow: offerings.eyebrow,
      title: offerings.title,
      accent: offerings.accent,
      aside: extras.services.aside,
      items: offerings.items.map((item, i) => ({
        icon: item.icon,
        title: item.title,
        kicker: extras.services.kickers[i] ?? "",
        description: item.body,
        accent: extras.services.accents[i] ?? service.accent,
        items: item.points,
      })),
    },
    orbit: extras.orbit,
    systems: extras.systems,
    split: extras.split,
    process: service.process,
    stack: service.stack,
    statement: service.statement,
    industries: service.industries,
    hire: service.hire,
    faqs: service.faqs,
    related: service.related,
    cta: service.cta,
  };
}

